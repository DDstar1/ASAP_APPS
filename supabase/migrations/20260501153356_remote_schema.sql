CREATE OR REPLACE FUNCTION public.append_waypoints(p_order_id bigint, p_new_waypoints jsonb, p_current_lat double precision, p_current_lng double precision)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  waypoint_count INT;
  total_waypoints INT;
  rider_uuid UUID;
BEGIN

  -- Count received waypoints
  waypoint_count := jsonb_array_length(p_new_waypoints);

  -- Insert each waypoint as a separate row
  INSERT INTO public.delivery_orders_waypoints (
    order_id,
    lat,
    long,
    created_at
  )
  SELECT
    p_order_id,
    (w->>'lat')::DOUBLE PRECISION,
    (w->>'lng')::DOUBLE PRECISION,
    COALESCE((w->>'timestamp')::timestamptz, now())
  FROM jsonb_array_elements(p_new_waypoints) w;

  -- Update current driver location in delivery_orders
    UPDATE public.riders_current_status
    SET 
      latitude = p_current_lat,
      longitude = p_current_lng,
      updated_at = now()
    WHERE id = rider_uuid;

  -- Count total waypoints for this order
  SELECT COUNT(*)
  INTO total_waypoints
  FROM public.delivery_orders_waypoints
  WHERE order_id = p_order_id;

  -- Return debug object
  RETURN jsonb_build_object(
    'success', true,
    'order_id', p_order_id,
    'driver_id', rider_uuid,
    'waypoints_received', waypoint_count,
    'total_waypoints_in_db', total_waypoints,
    'current_lat', p_current_lat,
    'current_lng', p_current_lng,
    'updated_at', now()
  );

END;
$function$
;

