CREATE OR REPLACE FUNCTION public.telegram_get_nearby_riders(user_lat double precision, user_lng double precision, radius_km double precision DEFAULT 10)
 RETURNS TABLE(id uuid, latitude numeric, longitude numeric, distance_km double precision)
 LANGUAGE sql
 STABLE
AS $function$
  SELECT id, latitude, longitude, distance_km
  FROM (
    SELECT
      r.id,
      r.latitude,
      r.longitude,
      ( 6371 * acos(
          LEAST(1.0, cos(radians(user_lat)) * cos(radians(r.latitude::DOUBLE PRECISION))
          * cos(radians(r.longitude::DOUBLE PRECISION) - radians(user_lng))
          + sin(radians(user_lat)) * sin(radians(r.latitude::DOUBLE PRECISION)))
      )) AS distance_km
    FROM public.app_riders_current_status r
    WHERE r.active_mode = 'rider'
  ) sub
  WHERE sub.distance_km <= radius_km
  ORDER BY sub.distance_km ASC;
$function$
;

